#!/bin/bash
# Turns the EFF large wordlist into VaultCore/Sources/VaultCore/PassphraseWords.swift.
# Usage: scripts/make-wordlist.sh path/to/eff_large_wordlist.txt
# Source: https://www.eff.org/files/2016/07/18/eff_large_wordlist.txt (CC BY 3.0, Electronic Frontier Foundation).
# The four hyphenated words are left out so that "-" can separate the words of a passphrase.
set -euo pipefail
source_list="$1"
expected_sha256="addd35536511597a02fa0a9ff1e5284677b8883b83e986e43f15a3db996b903e"
root="$(cd "$(dirname "$0")/.." && pwd)"
output="$root/VaultCore/Sources/VaultCore/PassphraseWords.swift"

actual_sha256="$(shasum -a 256 "$source_list" | cut -c1-64)"
if [ "$actual_sha256" != "$expected_sha256" ]; then
  echo "Unexpected wordlist (sha256 $actual_sha256), expected $expected_sha256" >&2
  exit 1
fi

{
  echo "// Generated by scripts/make-wordlist.sh. Do not edit by hand."
  echo "// EFF large wordlist for passphrases, by the Electronic Frontier Foundation, CC BY 3.0:"
  echo "// https://www.eff.org/dice. Source sha256 $expected_sha256."
  echo "// The four hyphenated words are removed, leaving 7772 words."
  echo ""
  echo "enum PassphraseWords {"
  echo "    static let all: [String] = text.split(separator: \"\\n\").map(String.init)"
  echo ""
  echo "    private static let text = \"\"\""
  cut -f2 "$source_list" | grep -v -e '-' | sed 's/^/        /'
  echo "        \"\"\""
  echo "}"
} > "$output"
echo "$output: $(cut -f2 "$source_list" | grep -cv -e '-') words"
